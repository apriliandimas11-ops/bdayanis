var spTracks = [
    { title: "Happy Birthday", artist: "Lagu Ulang Tahunmu", src: "assets/music/Happy Birthday.mp3" },
    { title: "Kita Lewati Berdua", artist: "Lagu Cinta", src: "assets/music/Kita Lewati Berdua.mp3" },
    { title: "Perfect", artist: "Ed Sheeran", src: "assets/music/Perfect.mp3" }
];
var spCurrentIndex = 0;
var spIsPlaying = false;

function initSpotifyPlayer() {
    var audio = document.getElementById("sp-audio");
    var playBtn = document.getElementById("sp-play");
    var prevBtn = document.getElementById("sp-prev");
    var nextBtn = document.getElementById("sp-next");
    var progressBar = document.getElementById("sp-progress-bar");
    var progress = document.getElementById("sp-progress");
    var thumb = document.getElementById("sp-progress-thumb");
    var currentTimeEl = document.getElementById("sp-current-time");
    var durationEl = document.getElementById("sp-duration");
    var playlistItems = document.querySelectorAll(".sp-playlist-item");

    // Load first track
    spLoadTrack(spCurrentIndex);

    // Play / Pause
    playBtn.addEventListener("click", function () {
        if (spIsPlaying) {
            spPause();
        } else {
            spPlay();
        }
    });

    // Previous
    prevBtn.addEventListener("click", function () {
        spCurrentIndex = (spCurrentIndex - 1 + spTracks.length) % spTracks.length;
        spLoadTrack(spCurrentIndex);
        spPlay();
    });

    // Next
    nextBtn.addEventListener("click", function () {
        spCurrentIndex = (spCurrentIndex + 1) % spTracks.length;
        spLoadTrack(spCurrentIndex);
        spPlay();
    });

    // Playlist click
    playlistItems.forEach(function (item) {
        item.addEventListener("click", function () {
            var index = parseInt(this.getAttribute("data-index"));
            if (index === spCurrentIndex && spIsPlaying) {
                spPause();
            } else {
                spCurrentIndex = index;
                spLoadTrack(spCurrentIndex);
                spPlay();
            }
        });
    });

    // Progress bar click/drag
    var isDragging = false;

    function seekFromEvent(e) {
        var rect = progressBar.getBoundingClientRect();
        var x = (e.touches ? e.touches[0].clientX : e.clientX) - rect.left;
        var pct = Math.max(0, Math.min(1, x / rect.width));
        if (audio.duration) {
            audio.currentTime = pct * audio.duration;
        }
    }

    progressBar.addEventListener("mousedown", function (e) {
        isDragging = true;
        seekFromEvent(e);
    });
    progressBar.addEventListener("touchstart", function (e) {
        isDragging = true;
        seekFromEvent(e);
    }, { passive: true });

    document.addEventListener("mousemove", function (e) {
        if (isDragging) seekFromEvent(e);
    });
    document.addEventListener("touchmove", function (e) {
        if (isDragging) seekFromEvent(e);
    }, { passive: true });

    document.addEventListener("mouseup", function () { isDragging = false; });
    document.addEventListener("touchend", function () { isDragging = false; });

    // Update progress
    audio.addEventListener("timeupdate", function () {
        if (!audio.duration) return;
        var pct = (audio.currentTime / audio.duration) * 100;
        progress.style.width = pct + "%";
        thumb.style.left = pct + "%";
        currentTimeEl.textContent = spFormatTime(audio.currentTime);
    });

    // Duration loaded
    audio.addEventListener("loadedmetadata", function () {
        durationEl.textContent = spFormatTime(audio.duration);
    });

    // Track ended -> next
    audio.addEventListener("ended", function () {
        spCurrentIndex = (spCurrentIndex + 1) % spTracks.length;
        spLoadTrack(spCurrentIndex);
        spPlay();
    });
}

function spLoadTrack(index) {
    var audio = document.getElementById("sp-audio");
    var titleEl = document.getElementById("sp-track-title");
    var artistEl = document.getElementById("sp-track-artist");
    var progress = document.getElementById("sp-progress");
    var thumb = document.getElementById("sp-progress-thumb");
    var currentTimeEl = document.getElementById("sp-current-time");
    var durationEl = document.getElementById("sp-duration");
    var playlistItems = document.querySelectorAll(".sp-playlist-item");

    var track = spTracks[index];
    audio.src = track.src;
    titleEl.textContent = track.title;
    artistEl.textContent = track.artist;
    progress.style.width = "0%";
    thumb.style.left = "0%";
    currentTimeEl.textContent = "00:00";
    durationEl.textContent = "00:00";

    // Update playlist highlight
    playlistItems.forEach(function (item) {
        item.classList.remove("active");
    });
    playlistItems[index].classList.add("active");
}

function spPlay() {
    var audio = document.getElementById("sp-audio");
    var playBtn = document.getElementById("sp-play");

    // Stop background music if playing
    var bgMusic = document.getElementById("bg-music");
    if (bgMusic && !bgMusic.paused) {
        bgMusic.pause();
        musicPlaying = false;
        var musicBtn = document.getElementById("music-btn");
        var musicIcon = document.getElementById("music-icon");
        if (musicBtn) musicBtn.classList.remove("playing");
        if (musicIcon) musicIcon.textContent = "🔇";
    }

    audio.play().then(function () {
        spIsPlaying = true;
        playBtn.textContent = "⏸";
    }).catch(function () {
        spIsPlaying = false;
    });
}

function spPause() {
    var audio = document.getElementById("sp-audio");
    var playBtn = document.getElementById("sp-play");
    audio.pause();
    spIsPlaying = false;
    playBtn.textContent = "▶";
}

function spFormatTime(sec) {
    if (!sec || isNaN(sec)) return "00:00";
    var m = Math.floor(sec / 60);
    var s = Math.floor(sec % 60);
    return (m < 10 ? "0" : "") + m + ":" + (s < 10 ? "0" : "") + s;
}

