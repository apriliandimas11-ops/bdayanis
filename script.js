function initCake() {
    var container = document.getElementById("candles-container");
    var messageEl = document.getElementById("cake-surprise-message");
    if(!container) return;
    container.innerHTML = "";
    candleStates = [false, false, false];

    for (var i = 0; i < 3; i++) {
        var candle = document.createElement("div");
        candle.className = "candle";
        candle.setAttribute("data-index", i);
        candle.innerHTML = '<div class="flame"></div>';

        candle.addEventListener("click", function(e) {
            var idx = parseInt(this.getAttribute("data-index"));
            if (candleStates[idx]) return;

            candleStates[idx] = true;
            this.classList.add("blown");

            // Explosion effect
            var rect = this.getBoundingClientRect();
            createExplosion(rect.left + rect.width / 2, rect.top);

            createSparkles("cake-section", 10);

            messageEl.classList.remove("show");
            setTimeout(function() {
                messageEl.textContent = candleMessages[idx];
                messageEl.classList.add("show");
            }, 300);

            checkAllCandles();
        });

        container.appendChild(candle);
    }
}

function createExplosion(x, y) {
    var colors = ['#ff6b8a', '#d4a574', '#fff8f0', '#ff9d00'];
    for(var i=0; i<30; i++) {
        var p = document.createElement("div");
        p.className = "explosion-particle";
        var angle = Math.random() * Math.PI * 2;
        var distance = Math.random() * 80 + 20;
        p.style.setProperty('--tx', Math.cos(angle) * distance + 'px');
        p.style.setProperty('--ty', Math.sin(angle) * distance + 'px');
        p.style.left = x + 'px';
        p.style.top = y + 'px';
        p.style.backgroundColor = colors[Math.random() * colors.length | 0];
        document.body.appendChild(p);
        setTimeout((function(el) { return function() { el.remove(); } })(p), 800);
    }
}

