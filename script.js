/* ==========================================
   PIN SCREEN
   ========================================== */

function initPIN() {
    const pinInputs = document.querySelectorAll(".pin-input");
    const btnEnter = document.getElementById("btn-enter");
    const pinError = document.getElementById("pin-error");
    const pinContainer = document.getElementById("pin-container");

    // Floating hearts & sparkles on lock screen
    createFloatingHearts("lock-hearts", 15);
    createSparkles("lock-sparkles", 20);

    // Auto-focus first input
    setTimeout(function () { pinInputs[0].focus(); }, 2500);

    // Input handling
    pinInputs.forEach(function (input, index) {
        input.addEventListener("input", function (e) {
            var value = e.target.value;
            // Only allow digits
            e.target.value = value.replace(/[^0-9]/g, "");

            if (e.target.value && index < pinInputs.length - 1) {
                pinInputs[index + 1].focus();
            }

            if (e.target.value) {
                e.target.classList.add("filled");
            } else {
                e.target.classList.remove("filled");
            }
        });

        input.addEventListener("keydown", function (e) {
            if (e.key === "Backspace" && !e.target.value && index > 0) {
                pinInputs[index - 1].focus();
                pinInputs[index - 1].value = "";
                pinInputs[index - 1].classList.remove("filled");
            }
        });

        // Paste support
        input.addEventListener("paste", function (e) {
            e.preventDefault();
            var paste = (e.clipboardData || window.clipboardData).getData("text").trim();
            if (/^\d{6}$/.test(paste)) {
                for (var i = 0; i < 6; i++) {
                    pinInputs[i].value = paste[i];
                    pinInputs[i].classList.add("filled");
                }
                pinInputs[5].focus();
            }
        });
    });

    // Enter button
    btnEnter.addEventListener("click", function () {
        var enteredPIN = "";
        pinInputs.forEach(function (input) {
            enteredPIN += input.value;
        });

        if (enteredPIN.length !== 6) {
            pinError.textContent = "Masukkan 6 digit PIN ❤️";
            pinError.classList.add("show");
            pinContainer.classList.add("shake");
            setTimeout(function () { pinContainer.classList.remove("shake"); }, 500);
            return;
        }

        if (enteredPIN === CONFIG.pin) {
            // PIN correct
            pinError.classList.remove("show");
            pinContainer.classList.add("success");
            btnEnter.textContent = "Berhasil ❤️";

            // Create falling hearts
            createFallingHearts();

            setTimeout(function () {
                showGiftScreen();
            }, 1500);
        } else {
            // PIN wrong
            pinError.textContent = "PIN yang kamu masukkan salah ❤️";
            pinError.classList.add("show");
            pinContainer.classList.add("shake");
            setTimeout(function () { pinContainer.classList.remove("shake"); }, 500);

            // Clear inputs
            pinInputs.forEach(function (input) {
                input.value = "";
                input.classList.remove("filled");
            });
            pinInputs[0].focus();
        }
    });

    // Enter key support
    document.addEventListener("keydown", function (e) {
        if (e.key === "Enter" && !document.getElementById("lock-screen").classList.contains("fade-out")) {
            btnEnter.click();
        }
    });
}

